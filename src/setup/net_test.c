int tn_format_roadshow_interface(const char *dev, ULONG unit, BOOL is_dhcp,
                                 const char *ip, const char *mask,
                                 char *out_buf, int out_max)
{
    if (!dev || !out_buf || out_max <= 0) return 0;

    int written = 0;
    if (is_dhcp) {
        written = snprintf(out_buf, out_max,
                           "device=%s\n"
                           "unit=%lu\n"
                           "configure=dhcp\n"
                           "iprequests=128\n"
                           "writerequests=128\n"
                           "requiresinitdelay=no\n",
                           dev, (unsigned long)unit);
    } else {
        written = snprintf(out_buf, out_max,
                           "device=%s\n"
                           "unit=%lu\n"
                           "address=%s\n"
                           "netmask=%s\n"
                           "iprequests=128\n"
                           "writerequests=128\n"
                           "requiresinitdelay=no\n",
                           dev, (unsigned long)unit, ip ? ip : "", mask ? mask : "");
    }
    return written;
}

