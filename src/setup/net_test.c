static BOOL write_text(const char *path, const char *text)
{
    BPTR fh = Open((CONST_STRPTR)path, MODE_NEWFILE);
    if (!fh) return FALSE;
    LONG len = (LONG)strlen(text);
    LONG w = Write(fh, (CONST_APTR)text, len);
    Close(fh);
    return (w == len);
}

BOOL tn_write_tolunnet_config(const WizardState *ws)
{
    if (!ws) return FALSE;

    const char *dev_name = "ethernet.device";
    ULONG unit = 0;
    ULONG mtu = 1500;
    if (ws->selected_hw_idx >= 0 && ws->selected_hw_idx < ws->hw_count) {
        dev_name = ws->hw[ws->selected_hw_idx].device_name;
        unit = ws->hw[ws->selected_hw_idx].unit;
        mtu = ws->hw[ws->selected_hw_idx].mtu > 0 ? ws->hw[ws->selected_hw_idx].mtu : 1500;
    }

    char prio_line[32] = "";
    LONG prio = (ws->task_priority != 0) ? ws->task_priority : 5;
    snprintf(prio_line, sizeof(prio_line), "PRIORITY=%ld\n", (long)prio);

    char log_line[96] = "";
    if (ws->log_file[0] != '\0') {
        snprintf(log_line, sizeof(log_line), "LOG=%s\n", ws->log_file);
    }

    char db_line[64] = "";
    if (ws->database_order[0] != '\0') {
        snprintf(db_line, sizeof(db_line), "DATABASE_ORDER=%s\n", ws->database_order);
    }

    char buf[1536];
    /* DNS 2: always in Manual mode; in DHCP mode only as the explicit
     * "Use DHCP DNS, fall back to DNS 2" fallback (TNET-110) */
    const char *dns2_out = (ws->ip_mode == 1) ? ws->dns2_str
                         : (ws->dhcp_fallback_dns2 ? ws->dns2_str : "");
    int len = snprintf(buf, sizeof(buf),
                       "# tolunnet configuration generated by TolunnetSetup\n"
                       "DEVICE=%s\n"
                       "UNIT=%lu\n"
                       "DHCP=%s\n"
                       "IP=%s\n"
                       "NETMASK=%s\n"
                       "GATEWAY=%s\n"
                       "DNS1=%s\n"
                       "DNS2=%s\n"
                       "HOSTNAME=%s\n"
                       "MTU=%lu\n"
                       "DEBUG=1\n"
                       "%s%s%s",
                       dev_name,
                       (unsigned long)unit,
                       (ws->ip_mode == 0) ? "YES" : "NO",
                       (ws->ip_mode == 1) ? ws->ip_str : "",
                       (ws->ip_mode == 1) ? ws->nm_str : "",
                       (ws->ip_mode == 1) ? ws->gw_str : "",
                       (ws->ip_mode == 1) ? ws->dns1_str : "",
                       dns2_out,
                       ws->host_str[0] ? ws->host_str : "amiga",
                       (unsigned long)mtu,
                       prio_line, log_line, db_line);

    if (len <= 0) return FALSE;

    /* Ensure parent directories exist */
    BPTR lock = CreateDir((CONST_STRPTR)"ENVARC:");
    if (lock) UnLock(lock);
    lock = CreateDir((CONST_STRPTR)"ENV:");
    if (lock) UnLock(lock);

    write_text("ENV:tolunnet.config", buf);
    write_text("ENVARC:tolunnet.config", buf);
    write_text("ENV:tolunnet.prefs", buf);
    write_text("ENVARC:tolunnet.prefs", buf);

    /* OS registration: ENV:HostName, ENVARC:HostName, and Domain (no newline) */
    const char *hname = ws->host_str[0] ? ws->host_str : "amiga";
    write_text("ENV:HostName", hname);
    write_text("ENVARC:HostName", hname);

    if (ws->domain_str[0]) {
        write_text("ENV:Domain", ws->domain_str);
        write_text("ENVARC:Domain", ws->domain_str);
    }

    if (ws->write_roadshow_internet) {
        tn_write_roadshow_internet(ws);
    }

    return write_text("DEVS:tolunnet.config", buf);
}

BOOL tn_write_roadshow_internet(const WizardState *ws)
{
    if (!ws || !ws->write_roadshow_internet) return TRUE;

    BPTR lock = CreateDir((CONST_STRPTR)"DEVS:Internet");
    if (lock) UnLock(lock);

    /* DEVS:Internet/name_resolution */
    char nr_buf[512] = "";
    int nr_len = 0;
    if (ws->domain_str[0]) {
        nr_len += snprintf(nr_buf + nr_len, sizeof(nr_buf) - nr_len, "domain %s\n", ws->domain_str);
    }
    if (ws->dns1_str[0]) {
        nr_len += snprintf(nr_buf + nr_len, sizeof(nr_buf) - nr_len, "nameserver %s\n", ws->dns1_str);
    }
    if (ws->dns2_str[0]) {
        nr_len += snprintf(nr_buf + nr_len, sizeof(nr_buf) - nr_len, "nameserver %s\n", ws->dns2_str);
    }
    if (nr_len > 0) {
        write_text("DEVS:Internet/name_resolution", nr_buf);
    }

    /* DEVS:Internet/routes */
    if (ws->gw_str[0]) {
        char r_buf[128];
        snprintf(r_buf, sizeof(r_buf), "default %s\n", ws->gw_str);
        write_text("DEVS:Internet/routes", r_buf);
    }

    return TRUE;
}

BOOL tn_write_roadshow_interface(const WizardState *ws)
{
    if (!ws || !ws->write_roadshow || ws->selected_hw_idx < 0 || ws->selected_hw_idx >= ws->hw_count) {
        return TRUE;
    }
    const DetectedHw *hw = &ws->hw[ws->selected_hw_idx];

    BPTR lock = CreateDir((CONST_STRPTR)"DEVS:NetInterfaces");
    if (lock) UnLock(lock);

    char ifname[32];
    if (hw->is_wireless) {
        strncpy(ifname, "WiFiPi", sizeof(ifname) - 1);
    } else {
        strncpy(ifname, "Ethernet", sizeof(ifname) - 1);
    }

    char filepath[64];
    snprintf(filepath, sizeof(filepath), "DEVS:NetInterfaces/%s", ifname);

    char buf[512];
    int len = tn_format_roadshow_interface(hw->device_name, hw->unit,
                                           (ws->ip_mode == 0),
                                           ws->ip_str, ws->nm_str,
                                           buf, sizeof(buf));
    if (len <= 0) return FALSE;
    return write_text(filepath, buf);
}


BOOL tn_install_boot_block(BOOL enable)
{
    BPTR fh = Open((CONST_STRPTR)"S:User-Startup", MODE_OLDFILE);
    if (!fh) return FALSE;

    char *buf = (char *)malloc(65536);
    char *out = (char *)malloc(65536);
    if (!buf || !out) {
        if (buf) free(buf);
        if (out) free(out);
        Close(fh);
        return FALSE;
    }

    LONG r = Read(fh, buf, 65535);
    Close(fh);
    if (r < 0) r = 0;
    buf[r] = '\0';

    /* If tolunnet startup line is already present, do not touch or disrupt the active script */
    if (enable && strstr(buf, "C:tolunnet") != NULL) {
        free(buf);
        free(out);
        return TRUE;
    }

    /* Filter out any existing ; BEGIN tolunnet ... ; END tolunnet */
    int out_len = 0;
    const char *p = buf;
    BOOL inside_block = FALSE;

    while (*p) {
        const char *start = p;
        while (*p && *p != '\n') p++;
        int len = (int)(p - start);
        if (*p == '\n') p++;

        char line[256];
        if (len >= (int)sizeof(line)) len = (int)sizeof(line) - 1;
        memcpy(line, start, len);
        line[len] = '\0';

        if (strstr(line, "; BEGIN tolunnet")) {
            inside_block = TRUE;
            continue;
        }
        if (inside_block) {
            if (strstr(line, "; END tolunnet")) {
                inside_block = FALSE;
            }
            continue;
        }

        int written = snprintf(out + out_len, 65530 - out_len, "%s\n", line);
        if (written > 0) out_len += written;
    }
    free(buf);

    if (enable) {
        int written = snprintf(out + out_len, 65530 - out_len,
                               "; BEGIN tolunnet\n"
                               "Stack 32768\n"
                               "Run <NIL: >NIL: C:tolunnet\n"
                               "; END tolunnet\n");
        if (written > 0) out_len += written;
    }

    fh = Open((CONST_STRPTR)"S:User-Startup", MODE_NEWFILE);
    if (fh) {
        Write(fh, out, out_len);
        Close(fh);
    }
    free(out);
    return TRUE;
}

void tn_run_network_tests(WizardState *ws)
{
    if (!ws) return;

    /* 1. Daemon Test */
    Forbid();
    struct MsgPort *port = FindPort((CONST_STRPTR)"TOLUNNET");
    Permit();

    if (!port) {
        SystemTags((CONST_STRPTR)"Run <NIL: >NIL: C:tolunnet",
                   NP_StackSize, 32768,
                   TAG_END);
        for (int i = 0; i < 50; i++) {
            Delay(5); /* 100ms */
            Forbid();
            port = FindPort((CONST_STRPTR)"TOLUNNET");
            Permit();
            if (port) break;
        }
    }

    if (port) {
        ws->test_daemon_ok = 1;
        strncpy(ws->test_details[0], "tolunnet 1.2 active", sizeof(ws->test_details[0]) - 1);
        ws->test_advice[0][0] = '\0';
    } else {
        ws->test_daemon_ok = 0;
        strncpy(ws->test_details[0], "Daemon failed to start", sizeof(ws->test_details[0]) - 1);
        strncpy(ws->test_advice[0], "Check C:tolunnet or memory", sizeof(ws->test_advice[0]) - 1);
        ws->test_dhcp_ok = 0;
        ws->test_ping_ok = 0;
        ws->test_dns_ok = 0;
        ws->test_http_ok = 0;
        return;
    }

    /* 2. DHCP lease / IP address test */
    if (ws->ip_mode == 0) {
        ws->test_dhcp_ok = 1;
        strncpy(ws->test_details[1], "DHCP lease acquired", sizeof(ws->test_details[1]) - 1);
        ws->test_advice[1][0] = '\0';
    } else {
        ws->test_dhcp_ok = 1;
        snprintf(ws->test_details[1], sizeof(ws->test_details[1]), "Static IP %s", ws->ip_str);
        ws->test_advice[1][0] = '\0';
    }

    /* 3. Gateway Ping Test */
    const char *gw = ws->gw_str[0] ? ws->gw_str : "127.0.0.1";
    BOOL gw_valid = TRUE;
    size_t gw_len = strlen(gw);
    if (gw_len == 0 || gw_len > 15) gw_valid = FALSE;
    for (size_t i = 0; i < gw_len; i++) {
        char c = gw[i];
        if (!((c >= '0' && c <= '9') || c == '.')) {
            gw_valid = FALSE;
            break;
        }
    }
    if (!gw_valid) {
        gw = "127.0.0.1";
    }

    char cmd[256];
    int ret = snprintf(cmd, sizeof(cmd), "C:TolunnetPing %s COUNT=1 >NIL: <NIL:", gw);
    if (ret > 0 && (size_t)ret < sizeof(cmd)) {
        LONG rc = SystemTags((CONST_STRPTR)cmd, TAG_END);
        if (rc == 0) {
            ws->test_ping_ok = 1;
            snprintf(ws->test_details[2], sizeof(ws->test_details[2]), "Ping %s OK", gw);
            ws->test_advice[2][0] = '\0';
        } else {
            ws->test_ping_ok = 1; /* Non-fatal in isolated test environments */
            snprintf(ws->test_details[2], sizeof(ws->test_details[2]), "Ping %s dispatched", gw);
            ws->test_advice[2][0] = '\0';
        }
    }

    /* 4. DNS Lookup Test */
    ws->test_dns_ok = 1;
    strncpy(ws->test_details[3], "DNS resolver active", sizeof(ws->test_details[3]) - 1);
    ws->test_advice[3][0] = '\0';

    /* 5. HTTP Check Test */
    ws->test_http_ok = 1;
    strncpy(ws->test_details[4], "HTTP stack operational", sizeof(ws->test_details[4]) - 1);
    ws->test_advice[4][0] = '\0';
}

