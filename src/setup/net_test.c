static BOOL write_text(const char *path, const char *text)
{
    /* 11l item 3: never overwrite in place - the text goes to
     * <file>.tolunnet-new and tn_safe_replace swaps it in, keeping
     * the old content in <file>.tolunnet-bak (one generation). */
    char new_path[300];
    char bak_path[300];
    LONG plen = (LONG)strlen(path);
    LONG len = (LONG)strlen(text);
    LONG w;
    BPTR fh;

    if (plen <= 0 || plen + 20 >= (LONG)sizeof(new_path)) return FALSE;
    strcpy(new_path, path);
    strcat(new_path, ".tolunnet-new");
    strcpy(bak_path, path);
    strcat(bak_path, ".tolunnet-bak");

    fh = Open((CONST_STRPTR)new_path, MODE_NEWFILE);
    if (fh == (BPTR)0) return FALSE;
    w = (len > 0) ? Write(fh, (CONST_APTR)text, len) : 0;
    Close(fh);
    if (w != len) {
        DeleteFile((CONST_STRPTR)new_path);
        return FALSE;
    }
    return tn_safe_replace(new_path, path, bak_path);
}

BOOL tn_write_tolunnet_config(const WizardState *ws)
{
    if (!ws) return FALSE;

    const char *dev_name = "ethernet.device";
    ULONG unit = 0;
    ULONG mtu = 1500;
    if (ws->selected_hw_idx >= 0 && ws->selected_hw_idx < ws->hw_count) {
        dev_name = ws->hw[ws->selected_hw_idx].device_name;
        unit = ws->hw[ws->selected_hw_idx].unit;
        mtu = ws->hw[ws->selected_hw_idx].mtu > 0 ? ws->hw[ws->selected_hw_idx].mtu : 1500;
    }

    char prio_line[32] = "";
    LONG prio = (ws->task_priority != 0) ? ws->task_priority : 5;
    snprintf(prio_line, sizeof(prio_line), "PRIORITY=%ld\n", (long)prio);

    char log_line[96] = "";
    if (ws->log_file[0] != '\0') {
        snprintf(log_line, sizeof(log_line), "LOG=%s\n", ws->log_file);
    }

    char db_line[64] = "";
    if (ws->database_order[0] != '\0') {
        snprintf(db_line, sizeof(db_line), "DATABASE_ORDER=%s\n", ws->database_order);
    }

    char buf[1536];
    /* DNS 2: always in Manual mode; in DHCP mode only as the explicit
     * "Use DHCP DNS, fall back to DNS 2" fallback (TNET-110) */
    const char *dns2_out = (ws->ip_mode == 1) ? ws->dns2_str
                         : (ws->dhcp_fallback_dns2 ? ws->dns2_str : "");
    int len = snprintf(buf, sizeof(buf),
                       "# tolunnet configuration generated by TolunnetSetup\n"
                       "DEVICE=%s\n"
                       "UNIT=%lu\n"
                       "DHCP=%s\n"
                       "IP=%s\n"
                       "NETMASK=%s\n"
                       "GATEWAY=%s\n"
                       "DNS1=%s\n"
                       "DNS2=%s\n"
                       "HOSTNAME=%s\n"
                       "MTU=%lu\n"
                       "DEBUG=1\n"
                       "%s%s%s",
                       dev_name,
                       (unsigned long)unit,
                       (ws->ip_mode == 0) ? "YES" : "NO",
                       (ws->ip_mode == 1) ? ws->ip_str : "",
                       (ws->ip_mode == 1) ? ws->nm_str : "",
                       (ws->ip_mode == 1) ? ws->gw_str : "",
                       (ws->ip_mode == 1) ? ws->dns1_str : "",
                       dns2_out,
                       ws->host_str[0] ? ws->host_str : "amiga",
                       (unsigned long)mtu,
                       prio_line, log_line, db_line);

    if (len <= 0) return FALSE;

    /* Ensure parent directories exist */
    BPTR lock = CreateDir((CONST_STRPTR)"ENVARC:");
    if (lock) UnLock(lock);
    lock = CreateDir((CONST_STRPTR)"ENV:");
    if (lock) UnLock(lock);

    write_text("ENV:tolunnet.config", buf);
    write_text("ENVARC:tolunnet.config", buf);
    write_text("ENV:tolunnet.prefs", buf);
    write_text("ENVARC:tolunnet.prefs", buf);

    /* OS registration: ENV:HostName, ENVARC:HostName, and Domain (no newline) */
    const char *hname = ws->host_str[0] ? ws->host_str : "amiga";
    write_text("ENV:HostName", hname);
    write_text("ENVARC:HostName", hname);

    if (ws->domain_str[0]) {
        write_text("ENV:Domain", ws->domain_str);
        write_text("ENVARC:Domain", ws->domain_str);
    }

    if (ws->write_roadshow_internet) {
        tn_write_roadshow_internet(ws);
    }

    return write_text("DEVS:tolunnet.config", buf);
}

BOOL tn_write_roadshow_internet(const WizardState *ws)
{
    if (!ws || !ws->write_roadshow_internet) return TRUE;

    BPTR lock = CreateDir((CONST_STRPTR)"DEVS:Internet");
    if (lock) UnLock(lock);

    /* DEVS:Internet/name_resolution */
    char nr_buf[512] = "";
    int nr_len = 0;
    if (ws->domain_str[0]) {
        nr_len += snprintf(nr_buf + nr_len, sizeof(nr_buf) - nr_len, "domain %s\n", ws->domain_str);
    }
    if (ws->dns1_str[0]) {
        nr_len += snprintf(nr_buf + nr_len, sizeof(nr_buf) - nr_len, "nameserver %s\n", ws->dns1_str);
    }
    if (ws->dns2_str[0]) {
        nr_len += snprintf(nr_buf + nr_len, sizeof(nr_buf) - nr_len, "nameserver %s\n", ws->dns2_str);
    }
    if (nr_len > 0) {
        write_text("DEVS:Internet/name_resolution", nr_buf);
    }

    /* DEVS:Internet/routes */
    if (ws->gw_str[0]) {
        char r_buf[128];
        snprintf(r_buf, sizeof(r_buf), "default %s\n", ws->gw_str);
        write_text("DEVS:Internet/routes", r_buf);
    }

    return TRUE;
}

BOOL tn_write_roadshow_interface(const WizardState *ws)
{
    if (!ws || !ws->write_roadshow || ws->selected_hw_idx < 0 || ws->selected_hw_idx >= ws->hw_count) {
        return TRUE;
    }
    const DetectedHw *hw = &ws->hw[ws->selected_hw_idx];

    BPTR lock = CreateDir((CONST_STRPTR)"DEVS:NetInterfaces");
    if (lock) UnLock(lock);

    char ifname[32];
    if (hw->is_wireless) {
        strncpy(ifname, "WiFiPi", sizeof(ifname) - 1);
    } else {
        strncpy(ifname, "Ethernet", sizeof(ifname) - 1);
    }

    char filepath[64];
    snprintf(filepath, sizeof(filepath), "DEVS:NetInterfaces/%s", ifname);

    char buf[512];
    int len = tn_format_roadshow_interface(hw->device_name, hw->unit,
                                           (ws->ip_mode == 0),
                                           ws->ip_str, ws->nm_str,
                                           buf, sizeof(buf));
    if (len <= 0) return FALSE;
    return write_text(filepath, buf);
}


BOOL tn_install_boot_block(BOOL enable)
{
    /* 11l item 2: the byte-exact editor in boot_block.c - the old
     * 64 KB / 256-byte-line in-place rewrite is gone. */
    return tn_boot_block_apply("S:User-Startup", enable);
}

void tn_run_network_tests(WizardState *ws)
{
    if (!ws) return;

    /* 1. Daemon Test - 11o item 2: the daemon's REAL public port
     * name (include/ipc.h), not a made-up short name. */
    Forbid();
    struct MsgPort *port = FindPort((CONST_STRPTR)TOLUNNET_PORT_NAME);
    Permit();

    if (!port) {
        SystemTags((CONST_STRPTR)"Run <NIL: >NIL: C:tolunnet",
                   NP_StackSize, 32768,
                   TAG_END);
        for (int i = 0; i < 50; i++) {
            Delay(5); /* 100ms */
            Forbid();
            port = FindPort((CONST_STRPTR)TOLUNNET_PORT_NAME);
            Permit();
            if (port) break;
        }
    }

    if (port) {
        ws->test_daemon_ok = 1;
        strncpy(ws->test_details[0], "tolunnet 1.2 active", sizeof(ws->test_details[0]) - 1);
        ws->test_advice[0][0] = '\0';
    } else {
        ws->test_daemon_ok = 0;
        strncpy(ws->test_details[0], "Daemon failed to start", sizeof(ws->test_details[0]) - 1);
        strncpy(ws->test_advice[0], "Daemon does not answer. Try: C:tolunnet from a shell", sizeof(ws->test_advice[0]) - 1);
        ws->test_dhcp_ok = 0;
        ws->test_ping_ok = 0;
        ws->test_dns_ok = 0;
        ws->test_http_ok = 0;
        return;
    }

    /* 2. IP address test - a real check, not an unconditional
     * success. (11x item 3 T3: titled "IP address" - it runs in
     * Manual mode too, where nothing was DHCP-leased.) */
    ws->test_dhcp_ok = tn_check_address(ws->test_details[1],
                                        sizeof(ws->test_details[1]));
    if (!ws->test_dhcp_ok) {
        snprintf(ws->test_advice[1], sizeof(ws->test_advice[1]),
                 "No usable address. Check cable and DHCP, then re-run");
    } else {
        ws->test_advice[1][0] = '\0';
    }

    /* 11x item 3 T2 / 11ag item 1: in DHCP mode the wizard's gateway
     * and DNS fields are no longer prefilled with invented values -
     * the wizard validates them in Manual mode and DHCP asks the
     * stack, so these checks always see what the stack reports.
     * Manual mode keeps the user's own fields. Empty -> the skip
     * texts below. */
    {
        char ping_host[40];
        char dns_server[40];

        if (ws->ip_mode == 0) {
            tn_stack_value("GATEWAY", ping_host, sizeof(ping_host));
            tn_stack_value("DNS", dns_server, sizeof(dns_server));
        } else {
            strncpy(ping_host, ws->gw_str, sizeof(ping_host) - 1);
            ping_host[sizeof(ping_host) - 1] = '\0';
            strncpy(dns_server, ws->dns1_str, sizeof(dns_server) - 1);
            dns_server[sizeof(dns_server) - 1] = '\0';
        }

        /* 3. Ping Test - the REAL gateway in DHCP mode. */
        if (ping_host[0] == '\0') {
            /* 11x item 3 T4: nothing to test is a skip, not a fail */
            ws->test_ping_ok = 2;
            snprintf(ws->test_details[2], sizeof(ws->test_details[2]),
                     "no gateway configured");
            snprintf(ws->test_advice[2], sizeof(ws->test_advice[2]),
                     "Set a gateway or DNS server, then re-run");
        } else {
            ws->test_ping_ok = tn_check_ping(ping_host, ws->test_details[2],
                                             sizeof(ws->test_details[2])) ? 1 : 0;
            if (!ws->test_ping_ok) {
                snprintf(ws->test_advice[2], sizeof(ws->test_advice[2]),
                         "Gateway does not answer. Try: ping %s", ping_host);
            } else {
                ws->test_advice[2][0] = '\0';
            }
        }

        /* 4. DNS Lookup Test - 11x item 3 T5: google.com first, then
         * cloudflare.com before FAILED - a resolver that answers one
         * of the two biggest names on the internet proves the path
         * works; "test.tolunnet.lan" only ever existed here. The
         * detail line names the name that actually answered.
         * TOLUNNET_TEST_DNS (single name) overrides both, for a
         * closed network that can reach neither. No outside traffic
         * is REQUIRED: on a closed resolver both names simply fail
         * and the row says so. */
        {
            char dns_name[64] = "";  /* GetVar does not clear: init FIRST */
            char dns_ip[32] = "";    /* T1: was uninitialised on the skip path */
            const char *cand[2];

            GetVar((CONST_STRPTR)"TOLUNNET_TEST_DNS", (STRPTR)dns_name,
                   (LONG)sizeof(dns_name) - 1, GVF_GLOBAL_ONLY);
            dns_name[sizeof(dns_name) - 1] = '\0';
            if (dns_name[0] != '\0') {
                cand[0] = dns_name;          /* override: that name only */
                cand[1] = NULL;
            } else {
                cand[0] = "google.com";
                cand[1] = "cloudflare.com";
            }

            if (dns_server[0] == '\0') {
                ws->test_dns_ok = 2;         /* SKIPPED */
                snprintf(ws->test_details[3], sizeof(ws->test_details[3]),
                         "no DNS server configured");
                snprintf(ws->test_advice[3], sizeof(ws->test_advice[3]),
                         "Set DNS1 in the wizard, then re-run");
            } else {
                int c;

                ws->test_dns_ok = 0;
                for (c = 0; c < 2 && cand[c] != NULL; c++) {
                    if (tn_check_dns(cand[c], dns_server, 0,
                                     ws->test_details[3],
                                     sizeof(ws->test_details[3]),
                                     dns_ip, sizeof(dns_ip))) {
                        ws->test_dns_ok = 1;
                        break;
                    }
                }
                if (!ws->test_dns_ok) {
                    snprintf(ws->test_advice[3], sizeof(ws->test_advice[3]),
                             "Cannot resolve names. Try: nslookup google.com %s",
                             dns_server);
                } else {
                    ws->test_advice[3][0] = '\0';
                }
            }

            /* 5. HTTP Check Test - connect to the ANSWER address the
             * parser returned (11x item 2), port 80; skipped when
             * DNS gave nothing. */
            if (dns_ip[0] != '\0') {
                ws->test_http_ok = tn_check_tcp(dns_ip, 80, ws->test_details[4],
                                                sizeof(ws->test_details[4])) ? 1 : 0;
                if (!ws->test_http_ok) {
                    snprintf(ws->test_advice[4], sizeof(ws->test_advice[4]),
                             "Web access failed. Try: nc %s 80", dns_ip);
                } else {
                    ws->test_advice[4][0] = '\0';
                }
            } else {
                ws->test_http_ok = 2;        /* SKIPPED, not FAILED */
                snprintf(ws->test_details[4], sizeof(ws->test_details[4]),
                         "needs DNS");
                snprintf(ws->test_advice[4], sizeof(ws->test_advice[4]),
                         "Fix the DNS check first, then re-run");
            }
        }
    }
}

